create extension if not exists pgcrypto;

create table if not exists public.event_teams (
  id uuid primary key default gen_random_uuid(),
  event_name text not null,
  team_name varchar(100) not null,
  amount integer not null check (amount >= 0),
  is_paid boolean not null default false,
  razorpay_order_id text,
  razorpay_payment_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.event_members (
  id bigint generated by default as identity primary key,
  team_id uuid not null references public.event_teams(id) on delete cascade,
  event_name text not null,
  name varchar(100) not null default '',
  usn varchar(10) not null,
  phone varchar(10) not null,
  created_at timestamptz not null default now()
);

alter table public.event_members add column if not exists name varchar(100) not null default '';
alter table public.event_members alter column usn type varchar(10);

create unique index if not exists event_members_event_usn_unique
on public.event_members(event_name, usn);

create unique index if not exists event_teams_event_team_name_unique
on public.event_teams(event_name, lower(team_name));

create index if not exists event_members_team_id_idx
on public.event_members(team_id);

-- Atomic registration transaction. The application calls this RPC instead of
-- inserting the team and members separately.
create or replace function public.register_event_team(
  p_team_id uuid,
  p_event_name text,
  p_team_name text,
  p_amount integer,
  p_members jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.event_teams (
    id, event_name, team_name, amount, is_paid
  ) values (
    p_team_id, p_event_name, p_team_name, p_amount, false
  );

  insert into public.event_members (
    team_id, event_name, name, usn, phone
  )
  select
    p_team_id,
    p_event_name,
    member->>'name',
    upper(member->>'usn'),
    regexp_replace(member->>'phone', '\\D', '', 'g')
  from jsonb_array_elements(p_members) as member;

  return p_team_id;
end;
$$;

grant execute on function public.register_event_team(uuid, text, text, integer, jsonb)
to service_role;
